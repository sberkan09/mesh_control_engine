#pragma once
// The game-module contract (scripting.md §2.1). A game module (game.dll / libgame.so) exports
// exactly one symbol, `mce_game_module`, returning a ModuleInfo that describes it:
//
//   static mce::ResultV install(mce::World& w) {
//       w.register_components<PlayerMove, Health>();
//       w.add_system(mce::Phase::FixedUpdate_Pre, "player_move", &player_move);
//       return mce::ok();
//   }
//   MCE_GAME_MODULE("platformer", 1, &install)
//
// The host installs the engine runtime systems (input, physics2d, audio bridge, render extract)
// before loading; `install` is the module's whole footprint on top of them: it registers components, events, systems and
// resources on the World it is handed, in an explicit order. Module rules (§2.4): no state
// outside the ECS (no mutable statics, no MCE_CVAR), no work in static initializers, main thread
// only. Code pointers registered into the World (systems, resource/event destructors) point
// into the module, so the World must be destroyed before unload_game_module().

#include "mce/ecs/world.h"
#include "mce/engine_version.h"  // MCE_ENGINE_ID, generated by CMake (cmake/EngineId.cmake)
#include "mce/result.h"

namespace mce {

// Hash of git-describe + build configuration, baked into the engine and every module built
// against it. A mismatch means a stale module build (Errc::EngineIdMismatch).
using EngineId = u64;

struct ModuleInfo {
    const char* name;          // "platformer": log tags, window title
    EngineId engine_id;        // must equal the host's MCE_ENGINE_ID
    u32 module_version;        // the game's own save-format version (FR-RUN-065)
    ResultV (*install)(World& world);
};

using ModuleEntryFn = const ModuleInfo* (*)();
inline constexpr const char* kModuleEntrySymbol = "mce_game_module";

}  // namespace mce

#if defined(_WIN32)
#define MCE_MODULE_EXPORT extern "C" __declspec(dllexport)
#else
#define MCE_MODULE_EXPORT extern "C" __attribute__((visibility("default")))
#endif

// Defines the module's single export. Use once, in one source file of the module.
#define MCE_GAME_MODULE(name_, version_, install_fn_)                                   \
    MCE_MODULE_EXPORT const ::mce::ModuleInfo* mce_game_module() {                      \
        static constexpr ::mce::ModuleInfo kModuleInfo{name_, MCE_ENGINE_ID, version_, \
                                                       install_fn_};                    \
        return &kModuleInfo;                                                            \
    }
