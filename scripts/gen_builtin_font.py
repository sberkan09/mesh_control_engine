#!/usr/bin/env python3
"""Bakes mce_ui's built-in font table from ProggyClean.ttf (Tristan Grimmer, MIT; the font Dear
ImGui embeds) at its native 16 px grid: printable ASCII as 7 x 13 one-bit rows. Writes
src/engine/ui/src/builtin_font_data.inc. Needs Pillow; the output is committed, so builds don't."""
import pathlib

from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parents[1]
TTF = ROOT / "samples" / "scene_demo" / "assets" / "fonts" / "ProggyClean.ttf"
OUT = ROOT / "src" / "engine" / "ui" / "src" / "builtin_font_data.inc"
W, H = 7, 13


def main():
    font = ImageFont.truetype(str(TTF), 16)
    ascent, descent = font.getmetrics()
    lines = ["// Generated by scripts/gen_builtin_font.py from ProggyClean.ttf (MIT). Do not edit.",
             "// One row per byte, bit 6 = leftmost pixel; codepoints 32..126.",
             "constexpr u32 kBuiltinAdvance = %d, kBuiltinAscent = %d, kBuiltinDescent = %d;" % (
                 int(font.getlength("A")), ascent, descent),
             "constexpr u32 kBuiltinW = %d, kBuiltinH = %d;" % (W, H),
             "constexpr u8 kBuiltinRows[95][%d] = {" % H]
    for c in range(32, 127):
        im = Image.new("L", (W, H), 0)
        d = ImageDraw.Draw(im)
        d.fontmode = "1"
        d.text((0, 0), chr(c), font=font, fill=255)
        rows = []
        for y in range(H):
            bits = 0
            for x in range(W):
                if im.getpixel((x, y)) > 127:
                    bits |= 1 << (W - 1 - x)
            rows.append("0x%02X" % bits)
        name = chr(c) if chr(c) not in "\\" else "backslash"
        lines.append("    {%s},  // %s" % (", ".join(rows), repr(name)))
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
