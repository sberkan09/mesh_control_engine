#!/usr/bin/env python3
"""mce content: the open-licence content ledger and its cook scripts (M-OPENWORLD D2).

    mce content list   [--kind K] [--tag T] [--license L] [--json]
    mce content info   <pack>
    mce content check  [--ledger f] [--online]
    mce content fetch  <pack> [--cache dir] [--file archive]
    mce content add    <pack> <project> [--only glob]... [--cache dir] [--file archive] [--dry-run]
    mce content verify <project>
    mce content credits <project>

The ledger (content/ledger.json in the engine tree, share/mce/content/ledger.json in an SDK) is the one list of
third-party packs the engine knows how to bring in. Every pack records its author, licence, homepage, the
archive URL with its SHA-256, the attribution text and the rules that turn archive members into project assets.
Only CC0 and CC-BY packs are admitted (check fails on anything else, NC, SA and ND included), so nothing the ledger
produces is non-redistributable. No archive is committed to the repository: `fetch` downloads one, verifies its
hash and keeps it in a cache (MCE_CONTENT_CACHE, default ~/.cache/mce/content); a pack whose download needs a
browser session (source kind "manual") takes the file with --file.

`add` extracts the selected members under <project>/assets/third_party/<pack>/, writes a `.mceasset` sidecar for
each (GUIDs are derived from the pack id and the path, so adding twice, or on another machine, gives the same
project), writes the pack's .mcmat materials, records the pack in <project>/third_party_content.json and rewrites
the generated block of <project>/CREDITS.md. `verify` fails when a file under assets/third_party/ belongs to no
recorded pack, when a recorded file changed or vanished, or when a recorded pack is no longer an allowed licence;
`credits` only rewrites the CREDITS block. Everything outside the generated block of CREDITS.md is left alone.
"""

import argparse
import fnmatch
import hashlib
import json
import os
import pathlib
import re
import shutil
import sys
import urllib.error
import urllib.request
import uuid
import zipfile

HERE = pathlib.Path(__file__).resolve()
ALLOWED_LICENSES = ("CC0-1.0", "CC-BY-3.0", "CC-BY-4.0")
KINDS = ("models", "textures", "audio", "animations", "hdri", "mixed")
SOURCE_KINDS = ("http", "manual")
IMPORTER_BY_EXT = {
    ".glb": "gltf", ".gltf": "gltf",
    ".png": "texture", ".jpg": "texture", ".jpeg": "texture", ".tga": "texture", ".bmp": "texture", ".hdr": "texture", ".exr": "texture",
    ".wav": "wav", ".ogg": "ogg", ".mp3": "mp3", ".flac": "flac",
}
LOCK_NAME = "third_party_content.json"
THIRD_PARTY = "assets/third_party"
CREDITS_BEGIN = "<!-- mce-content:begin (generated by `mce content`; do not edit between the markers) -->"
CREDITS_END = "<!-- mce-content:end -->"
GUID_NAMESPACE = uuid.UUID("5c1d0a38-6f0e-4a1e-9a57-0b7f3f0f6d11")
ID_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
SHA_RE = re.compile(r"^[0-9a-f]{64}$")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
USER_AGENT = "mce-content/1 (+https://github.com/sberkan09/mesh_control_engine)"


class ContentError(Exception):
    pass


def ledger_path():
    for p in (HERE.parents[2] / "content" / "ledger.json",  # the engine tree (tools/mce_cli/)
              HERE.parents[1] / "share" / "mce" / "content" / "ledger.json"):  # an SDK (bin/)
        if p.is_file():
            return p
    return HERE.parents[2] / "content" / "ledger.json"


def read_json(path):
    with open(path, "rb") as f:
        return json.loads(f.read().decode("utf-8-sig"))


def dumps(doc):
    """indent=2 JSON with arrays of numbers kept on one line, the way the engine's own text assets are written."""
    text = json.dumps(doc, indent=2, ensure_ascii=False)
    return re.sub(r"\[\s+(-?[\d.eE+-]+(?:,\s+-?[\d.eE+-]+)*)\s+\]", lambda m: "[" + re.sub(r",\s+", ", ", m.group(1)) + "]", text)


def write_json(path, doc):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(dumps(doc) + "\n")


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def load_ledger(path=None):
    path = pathlib.Path(path) if path else ledger_path()
    try:
        doc = read_json(path)
    except (OSError, ValueError) as e:
        raise ContentError(f"cannot read the ledger {path}: {e}")
    return doc


def find_pack(ledger, pack_id):
    for p in ledger.get("packs", []):
        if p.get("id") == pack_id:
            return p
    known = ", ".join(p.get("id", "?") for p in ledger.get("packs", []))
    raise ContentError(f"no pack '{pack_id}' in the ledger (known: {known})")


# ---- validation ------------------------------------------------------------------------------------------

def safe_rel(path):
    """True for a relative path with no '..', no drive and no leading slash."""
    if not isinstance(path, str) or path.startswith(("/", "\\")) or re.match(r"^[A-Za-z]:", path):
        return False
    return ".." not in path.replace("\\", "/").split("/")


def validate_ledger(doc):
    """Every problem found, as a list of strings (empty = valid)."""
    errs = []

    def err(where, msg):
        errs.append(f"{where}: {msg}")

    if doc.get("version") != 1:
        err("ledger", "'version' must be 1")
    licenses = doc.get("licenses")
    if not isinstance(licenses, dict) or not licenses:
        err("ledger", "'licenses' must be a table of the admitted licences")
        licenses = {}
    for lid, lic in licenses.items():
        where = f"licenses.{lid}"
        if lid not in ALLOWED_LICENSES:
            err(where, f"licence not admitted (only {', '.join(ALLOWED_LICENSES)}; NC, SA and ND are never admitted)")
        if not isinstance(lic, dict):
            err(where, "must be an object")
            continue
        if not isinstance(lic.get("name"), str) or not lic.get("name"):
            err(where, "'name' is missing")
        if not str(lic.get("url", "")).startswith("https://"):
            err(where, "'url' must be an https URL")
        if not isinstance(lic.get("attribution_required"), bool):
            err(where, "'attribution_required' must be true or false")
        elif lid.startswith("CC-BY") and not lic["attribution_required"]:
            err(where, "a CC-BY licence requires attribution")
    packs = doc.get("packs")
    if not isinstance(packs, list):
        err("ledger", "'packs' must be a list")
        return errs
    seen = set()
    for i, p in enumerate(packs):
        pid = p.get("id") if isinstance(p, dict) else None
        where = f"packs[{pid or i}]"
        if not isinstance(p, dict):
            err(where, "must be an object")
            continue
        if not isinstance(pid, str) or not ID_RE.match(pid):
            err(where, "'id' must be lowercase words joined by '-'")
        elif pid in seen:
            err(where, "duplicate id")
        seen.add(pid)
        for key in ("title", "author"):
            if not isinstance(p.get(key), str) or not p.get(key).strip():
                err(where, f"'{key}' is missing")
        if p.get("kind") not in KINDS:
            err(where, f"'kind' must be one of {', '.join(KINDS)}")
        if not isinstance(p.get("tags"), list) or not all(isinstance(t, str) for t in p.get("tags", [])):
            err(where, "'tags' must be a list of strings")
        if not str(p.get("homepage", "")).startswith("https://"):
            err(where, "'homepage' must be an https URL")
        if not DATE_RE.match(str(p.get("retrieved", ""))):
            err(where, "'retrieved' must be the date the licence was read, YYYY-MM-DD")
        lic = p.get("license")
        if lic not in licenses:
            err(where, f"licence '{lic}' is not in the ledger's licence table")
        if lic in licenses and isinstance(licenses[lic], dict):
            if licenses[lic].get("attribution_required") and not str(p.get("attribution", "")).strip():
                err(where, f"{lic} requires an 'attribution' line to credit")
        if not str(p.get("license_url", "")).startswith("https://"):
            err(where, "'license_url' must be an https URL (the page or file that states the licence)")
        src = p.get("source")
        if not isinstance(src, dict) or src.get("kind") not in SOURCE_KINDS:
            err(where, f"'source.kind' must be one of {', '.join(SOURCE_KINDS)}")
            src = {}
        if src.get("kind") == "http":
            if not str(src.get("url", "")).startswith("https://"):
                err(where, "'source.url' must be an https URL")
            if not SHA_RE.match(str(src.get("sha256", ""))):
                err(where, "'source.sha256' must be 64 lowercase hex digits (a download is always pinned)")
            if not isinstance(src.get("size"), int) or src.get("size", 0) <= 0:
                err(where, "'source.size' must be the archive size in bytes")
        elif src.get("kind") == "manual":
            if not str(src.get("page", "")).startswith("https://"):
                err(where, "'source.page' must be the https page the file is downloaded from")
            if not str(src.get("instructions", "")).strip():
                err(where, "'source.instructions' must say what to download")
            if "sha256" in src and not SHA_RE.match(str(src["sha256"])):
                err(where, "'source.sha256' must be 64 lowercase hex digits")
        if src.get("kind") in SOURCE_KINDS and src.get("archive", "zip") not in ("zip", "file"):
            err(where, "'source.archive' must be \"zip\" or \"file\"")
        lm = src.get("license_member")
        if lm is not None and (not isinstance(lm, str) or not safe_rel(lm)):
            err(where, "'source.license_member' must be a path inside the archive")
        cook = p.get("cook")
        if not isinstance(cook, list) or not cook:
            err(where, "'cook' must list at least one extraction rule")
            cook = []
        for j, r in enumerate(cook):
            rw = f"{where}.cook[{j}]"
            if not isinstance(r, dict):
                err(rw, "must be an object")
                continue
            if not isinstance(r.get("from", ""), str) or not safe_rel(r.get("from", "")):
                err(rw, "'from' must be a relative archive prefix")
            inc = r.get("include")
            if not isinstance(inc, list) or not inc or not all(isinstance(x, str) for x in inc):
                err(rw, "'include' must be a non-empty list of glob patterns")
            if not isinstance(r.get("to", ""), str) or not safe_rel(r.get("to", "")):
                err(rw, "'to' must be a relative directory under the pack's folder")
            for s in r.get("settings", []):
                if not isinstance(s, dict) or not isinstance(s.get("match"), str) or not isinstance(s.get("settings", {}), dict):
                    err(rw, "each 'settings' entry needs 'match' (a glob) and a 'settings' object")
                elif "importer" in s and s["importer"] not in set(IMPORTER_BY_EXT.values()):
                    err(rw, f"unknown importer '{s['importer']}'")
        for j, m in enumerate(p.get("materials", [])):
            mw = f"{where}.materials[{j}]"
            if not isinstance(m, dict) or not safe_rel(m.get("path", "")) or not str(m.get("path", "")).endswith(".mcmat"):
                err(mw, "'path' must be a relative .mcmat path under the pack's folder")
            elif not isinstance(m.get("textures", {}), dict):
                err(mw, "'textures' must map a material slot to a file")
            orm = m.get("orm")
            if orm is not None:
                if not isinstance(orm, dict) or not isinstance(orm.get("roughness"), str) or not safe_rel(orm.get("out", "")):
                    err(mw, "'orm' needs 'roughness' (a file the cook rules extract) and 'out' (the packed texture's path)")
                elif "metallic_roughness" in m.get("textures", {}):
                    err(mw, "'orm' and textures.metallic_roughness both set the same slot")
    return errs


# ---- fetching --------------------------------------------------------------------------------------------

def cache_dir(arg=None):
    d = arg or os.environ.get("MCE_CONTENT_CACHE") or os.path.join(os.path.expanduser("~"), ".cache", "mce", "content")
    return pathlib.Path(d)


def cached_name(pack):
    src = pack["source"]
    sha = src.get("sha256", "unpinned")
    ext = ".zip" if src.get("archive", "zip") == "zip" else os.path.splitext(src.get("filename", "file.bin"))[1] or ".bin"
    return f"{pack['id']}-{sha[:12]}{ext}"


def download(url, dest, opener=None):
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    opener = opener or urllib.request.urlopen
    tmp = dest.with_suffix(dest.suffix + ".part")
    try:
        with opener(req, timeout=120) as r, open(tmp, "wb") as f:
            headers = getattr(r, "headers", None)
            if headers is not None and headers.get_content_type() == "text/html":
                # a host that moved to browser-only downloads redirects the old link to a web page
                raise ContentError(f"{url} returned a web page ({getattr(r, 'url', url)}), not the file; the host "
                                   "no longer serves it to scripts: make its ledger entry `manual` (user guide 5.3)")
            shutil.copyfileobj(r, f)
    except (urllib.error.URLError, OSError) as e:
        if tmp.exists():
            tmp.unlink()
        raise ContentError(f"download of {url} failed: {e}")
    except ContentError:
        if tmp.exists():
            tmp.unlink()
        raise
    return tmp


def fetch_pack(pack, cache, local_file=None, opener=None):
    """Path of the verified archive in the cache. A mismatch deletes the download and raises."""
    src = pack["source"]
    cache.mkdir(parents=True, exist_ok=True)
    dest = cache / cached_name(pack)
    want = src.get("sha256")
    if dest.is_file() and want and sha256_file(dest) == want:
        return dest
    if local_file:
        tmp = cache / (dest.name + ".part")
        shutil.copyfile(local_file, tmp)
    elif src["kind"] == "manual":
        raise ContentError(f"'{pack['id']}' cannot be downloaded by a script: {src['instructions']}\n"
                           f"  page: {src['page']}\n  then run: mce content fetch {pack['id']} --file <the downloaded file>")
    else:
        tmp = download(src["url"], dest, opener)
    got = sha256_file(tmp)
    if want and got != want:
        tmp.unlink()
        raise ContentError(f"'{pack['id']}': sha256 is {got}, the ledger pins {want}. The upstream file changed; "
                           "re-read its licence, then update the ledger entry (source.sha256, size, retrieved) in a PR.")
    if not want:
        print(f"mce content: '{pack['id']}' has no pinned sha256 yet; this file is {got} (add it to the ledger)", file=sys.stderr)
    os.replace(tmp, dest)
    return dest


# ---- PNG (just enough to pack an ORM texture: 8-bit, not interlaced) -----------------------------------

def decode_png(data):
    """(width, height, channels, bytearray of rows) of an 8-bit non-interlaced greyscale / RGB / RGBA PNG."""
    import struct
    import zlib
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ContentError("not a PNG file")
    pos, idat, hdr = 8, [], None
    while pos + 8 <= len(data):
        n, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + n]
        pos += 12 + n
        if kind == b"IHDR":
            hdr = struct.unpack(">IIBBBBB", body)
        elif kind == b"IDAT":
            idat.append(body)
        elif kind == b"IEND":
            break
    if hdr is None:
        raise ContentError("PNG without IHDR")
    w, h, depth, ctype, _, _, interlace = hdr
    channels = {0: 1, 2: 3, 4: 2, 6: 4}.get(ctype)
    if depth != 8 or channels is None or interlace:
        raise ContentError(f"cannot pack this PNG (bit depth {depth}, colour type {ctype}, interlace {interlace}): "
                           "8-bit greyscale, RGB or RGBA without interlacing only")
    raw = zlib.decompress(b"".join(idat))
    stride = w * channels
    if len(raw) != h * (stride + 1):
        raise ContentError("PNG data has the wrong size")
    out = bytearray(h * stride)
    prev = bytearray(stride)
    for y in range(h):
        f = raw[y * (stride + 1)]
        row = bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        if f == 1:
            for i in range(channels, stride):
                row[i] = (row[i] + row[i - channels]) & 255
        elif f == 2:
            row = bytearray((a + b) & 255 for a, b in zip(row, prev))
        elif f == 3:
            for i in range(stride):
                left = row[i - channels] if i >= channels else 0
                row[i] = (row[i] + ((left + prev[i]) >> 1)) & 255
        elif f == 4:
            for i in range(stride):
                a = row[i - channels] if i >= channels else 0
                b = prev[i]
                c = prev[i - channels] if i >= channels else 0
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                pred = a if (pa <= pb and pa <= pc) else (b if pb <= pc else c)
                row[i] = (row[i] + pred) & 255
        elif f != 0:
            raise ContentError(f"PNG row filter {f} is not valid")
        out[y * stride:(y + 1) * stride] = row
        prev = row
    return w, h, channels, out


def encode_png_rgb(w, h, rgb):
    """A deterministic 8-bit RGB PNG (no filtering, zlib level 9, no metadata)."""
    import struct
    import zlib

    def chunk(kind, body):
        return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body))
    rows = b"".join(b"\x00" + bytes(rgb[y * w * 3:(y + 1) * w * 3]) for y in range(h))
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)) + \
        chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b"")


def pack_orm(rough_png, ao_png=None, metallic=0):
    """The engine's metallic-roughness texture from a roughness map and an optional occlusion map:
    R occlusion (255 when absent), G roughness, B metallic (a constant). Returns PNG bytes."""
    w, h, ch, rough = decode_png(rough_png)
    n = w * h
    g = rough[0::ch][:n] if ch in (1, 3, 4) else rough[0::2][:n]  # greyscale: the sample; RGB(A): the red channel
    if ao_png is not None:
        aw, ah, ach, ao = decode_png(ao_png)
        if (aw, ah) != (w, h):
            raise ContentError(f"the occlusion map is {aw}x{ah}, the roughness map {w}x{h}")
        r = ao[0::ach][:n] if ach in (1, 3, 4) else ao[0::2][:n]
    else:
        r = bytes([255]) * n
    rgb = bytearray(n * 3)
    rgb[0::3] = r
    rgb[1::3] = g
    rgb[2::3] = bytes([max(0, min(255, round(metallic * 255)))]) * n
    return encode_png_rgb(w, h, rgb)


# ---- cooking ---------------------------------------------------------------------------------------------

def guid_for(pack_id, rel):
    return str(uuid.uuid5(GUID_NAMESPACE, f"{pack_id}/{rel}"))


class Archive:
    """A pack's download as a list of members: a zip, or (archive "file") one file named by source.filename."""

    def __init__(self, pack, path):
        self.single = pack["source"].get("archive", "zip") == "file"
        self.path = path
        self.name = pack["source"].get("filename", os.path.basename(path)) if self.single else None
        self.zip = None if self.single else zipfile.ZipFile(path)

    def names(self):
        return [self.name] if self.single else self.zip.namelist()

    def read(self, name):
        if self.single:
            return pathlib.Path(self.path).read_bytes()
        return self.zip.read(name)

    def close(self):
        if self.zip:
            self.zip.close()


def plan_members(pack, names):
    """[(archive member, destination path relative to the pack folder, rule)] in archive order, first rule wins."""
    out = []
    claimed = set()
    for name in names:
        if name.endswith("/"):
            continue
        if not safe_rel(name):
            raise ContentError(f"'{pack['id']}': archive member '{name}' escapes the destination")
        for rule in pack["cook"]:
            prefix = rule.get("from", "")
            if prefix and not name.startswith(prefix):
                continue
            rel = name[len(prefix):]
            if not any(fnmatch.fnmatchcase(rel, pat) for pat in rule["include"]):
                continue
            if any(fnmatch.fnmatchcase(rel, pat) for pat in rule.get("exclude", [])):
                continue
            dest = (rule["to"].rstrip("/") + "/" if rule["to"] else "") + rel
            if dest in claimed:
                raise ContentError(f"'{pack['id']}': two members map to {dest}")
            claimed.add(dest)
            out.append((name, dest, rule))
            break
    return out


def sidecar_for(pack, dest, rule):
    ext = os.path.splitext(dest)[1].lower()
    importer = IMPORTER_BY_EXT.get(ext)
    settings = {}
    for s in rule.get("settings", []):
        if fnmatch.fnmatchcase(os.path.basename(dest), s["match"]) or fnmatch.fnmatchcase(dest, s["match"]):
            importer = s.get("importer", importer)
            settings.update(s["settings"])
    if importer is None:
        return None
    return {"guid": guid_for(pack["id"], dest), "importer": importer, "importer_version": 1, "settings": settings}


def material_doc(pack, mat, dests, extra=None):
    base = mat["path"][: -len(".mcmat")]
    doc = {"format": "mce-material", "version": 1, "guid": guid_for(pack["id"], mat["path"]),
           "name": os.path.basename(base),
           "base_color": mat.get("base_color", [1, 1, 1, 1]), "metallic": mat.get("metallic", 0),
           "roughness": mat.get("roughness", 1), "emissive": [0, 0, 0], "alpha_mode": "opaque",
           "alpha_cutoff": 0.5, "double_sided": False, "unlit": False}
    if "uv_scale" in mat:
        doc["uv_scale"] = mat["uv_scale"]
    textures = {}
    slots = dict(mat.get("textures", {}))
    slots.update(extra or {})
    if extra:  # a packed ORM texture carries roughness and metallic: the factors scale it, so they are 1
        doc["roughness"], doc["metallic"] = 1, 1
    for slot, rel in sorted(slots.items()):
        if rel not in dests:
            raise ContentError(f"'{pack['id']}': material {mat['path']} uses {rel}, which no cook rule extracts")
        textures[slot] = "guid:" + guid_for(pack["id"], rel)
    doc["textures"] = textures
    return doc


def add_pack(pack, project, archive, only=None, dry_run=False):
    """Extracts `pack` from `archive` into `project`. Returns the lock entry."""
    project = pathlib.Path(project)
    if not (project / "assets").is_dir():
        raise ContentError(f"{project} has no assets/ folder: pass a project directory")
    root = project / THIRD_PARTY / pack["id"]
    z = Archive(pack, archive)
    try:
        plan = plan_members(pack, z.names())
        if only:
            plan = [x for x in plan if any(fnmatch.fnmatchcase(x[1], pat) for pat in only)]
        if not plan:
            raise ContentError(f"'{pack['id']}': the cook rules{' and --only' if only else ''} select no archive member")
        dests = {d for _, d, _ in plan}
        member_of = {d: n for n, d, _ in plan}
        files = {}
        for name, dest, rule in plan:
            data = z.read(name)
            files[dest] = hashlib.sha256(data).hexdigest()
            if dry_run:
                continue
            target = root / dest
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            sc = sidecar_for(pack, dest, rule)
            if sc and not (target.parent / (target.name + ".mceasset")).exists():
                write_json(target.parent / (target.name + ".mceasset"), sc)
        lic_member = pack["source"].get("license_member")
        if not dry_run:
            root.mkdir(parents=True, exist_ok=True)
            if lic_member:  # the pack's own licence text
                (root / "LICENSE.txt").write_bytes(z.read(lic_member))
            else:
                (root / "LICENSE.txt").write_text(
                    f"{pack['title']}\nby {pack['author']}\nLicense: {pack['license']} ({pack['license_url']})\n"
                    f"Source: {pack['homepage']}\n" + (f"Attribution: {pack['attribution']}\n" if pack.get("attribution") else ""),
                    encoding="utf-8", newline="\n")
    finally:
        z.close()
    materials = []
    orm_files = {}
    for mat in pack.get("materials", []):
        orm = mat.get("orm")
        needed = list(mat.get("textures", {}).values()) + ([orm["roughness"]] + ([orm["ao"]] if orm.get("ao") else []) if orm else [])
        if only and not any(fnmatch.fnmatchcase(mat["path"], pat) for pat in only) and not all(t in dests for t in needed):
            continue
        for rel in needed:
            if rel not in dests:
                raise ContentError(f"'{pack['id']}': material {mat['path']} uses {rel}, which no cook rule extracts")
        extra = {}
        if orm:
            z = Archive(pack, archive)
            try:
                data = pack_orm(z.read(member_of[orm["roughness"]]), z.read(member_of[orm["ao"]]) if orm.get("ao") else None,
                                orm.get("metallic", 0))
            finally:
                z.close()
            out = orm["out"]
            orm_files[out] = data
            extra = {"metallic_roughness": out}
            dests = dests | {out}
        doc = material_doc(pack, mat, dests, extra)
        materials.append(mat["path"])
        if not dry_run:
            write_json(root / mat["path"], doc)
            for out, data in orm_files.items():
                target = root / out
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(data)
                write_json(target.parent / (target.name + ".mceasset"),
                           {"guid": guid_for(pack["id"], out), "importer": "texture", "importer_version": 1,
                            "settings": {"srgb": False}})
    for out, data in orm_files.items():
        files[out] = hashlib.sha256(data).hexdigest()
    return {"id": pack["id"], "title": pack["title"], "author": pack["author"], "license": pack["license"],
            "license_url": pack["license_url"], "homepage": pack["homepage"], "attribution": pack.get("attribution", ""),
            "archive_sha256": pack["source"].get("sha256") or sha256_file(archive),
            "files": dict(sorted(files.items())), "materials": sorted(materials)}


# ---- project lock and credits ----------------------------------------------------------------------------

def read_lock(project):
    p = pathlib.Path(project) / LOCK_NAME
    if not p.is_file():
        return {"version": 1, "packs": []}
    return read_json(p)


def write_lock(project, lock):
    lock["packs"] = sorted(lock["packs"], key=lambda e: e["id"])
    write_json(pathlib.Path(project) / LOCK_NAME, lock)


def credits_block(lock):
    lines = [CREDITS_BEGIN, "", "## Third-party content (open licences)", "",
             "| Pack | Author | Licence | Source |", "|---|---|---|---|"]
    for e in lock["packs"]:
        lines.append(f"| {e['title']} (`assets/third_party/{e['id']}/`) | {e['author']} | "
                     f"[{e['license']}]({e['license_url']}) | {e['homepage']} |")
    notes = [e for e in lock["packs"] if e.get("attribution") and e["license"].startswith("CC-BY")]
    if notes:
        lines += ["", "Attribution required by the licences above:", ""]
        for e in notes:
            lines.append(f"- {e['attribution']}")
    lines += ["", CREDITS_END]
    return "\n".join(lines) + "\n"


def write_credits(project, lock):
    path = pathlib.Path(project) / "CREDITS.md"
    text = path.read_text(encoding="utf-8") if path.is_file() else "# Credits\n\n"
    b, e = text.find(CREDITS_BEGIN), text.find(CREDITS_END)
    if b >= 0 and e > b:
        text = text[:b].rstrip("\n") + "\n\n" + text[e + len(CREDITS_END):].lstrip("\n")
    text = text.rstrip("\n") + "\n"
    if lock["packs"]:
        text += "\n" + credits_block(lock)
    path.write_text(text, encoding="utf-8", newline="\n")


def verify_project(project, ledger=None):
    """Problems found in a project's third-party content (empty = clean)."""
    project = pathlib.Path(project)
    lock = read_lock(project)
    problems = []
    recorded = set()
    for e in lock["packs"]:
        if e.get("license") not in ALLOWED_LICENSES:
            problems.append(f"{e['id']}: licence '{e.get('license')}' is not an admitted open licence")
        if e.get("license", "").startswith("CC-BY") and not e.get("attribution"):
            problems.append(f"{e['id']}: CC-BY content without an attribution line")
        root = project / THIRD_PARTY / e["id"]
        for rel, sha in e["files"].items():
            p = root / rel
            recorded.add(p.resolve())
            recorded.add((p.parent / (p.name + ".mceasset")).resolve())
            if not p.is_file():
                problems.append(f"{e['id']}: {rel} is recorded but missing")
            elif sha256_file(p) != sha:
                problems.append(f"{e['id']}: {rel} differs from the recorded hash")
        for rel in e.get("materials", []):
            recorded.add((root / rel).resolve())
        recorded.add((root / "LICENSE.txt").resolve())
        if ledger is not None:
            try:
                pack = find_pack(ledger, e["id"])
            except ContentError:
                problems.append(f"{e['id']}: not in the ledger any more")
                continue
            if pack["license"] != e["license"]:
                problems.append(f"{e['id']}: the ledger now says {pack['license']}, the project recorded {e['license']}")
    tp = project / THIRD_PARTY
    if tp.is_dir():
        for f in sorted(tp.rglob("*")):
            if f.is_file() and f.resolve() not in recorded:
                problems.append(f"{f.relative_to(project).as_posix()}: not recorded in {LOCK_NAME} "
                                "(add the pack with `mce content add`; unlicensed files are not allowed)")
    return problems


# ---- commands --------------------------------------------------------------------------------------------

def cmd_list(args, ledger):
    packs = ledger["packs"]
    if args.kind:
        packs = [p for p in packs if p["kind"] == args.kind]
    if args.tag:
        packs = [p for p in packs if args.tag in p["tags"]]
    if args.license:
        packs = [p for p in packs if p["license"] == args.license]
    if args.json:
        print(json.dumps([{k: p[k] for k in ("id", "title", "kind", "author", "license", "tags")} for p in packs], indent=2))
        return 0
    for p in packs:
        print(f"{p['id']:<34} {p['kind']:<10} {p['license']:<9} {p['title']} ({p['author']})")
    return 0


def cmd_info(args, ledger):
    print(json.dumps(find_pack(ledger, args.pack), indent=2))
    return 0


def cmd_check(args, ledger):
    errs = validate_ledger(ledger)
    if args.online and not errs:
        for p in ledger["packs"]:
            url = p["source"].get("url") or p["source"].get("page")
            req = urllib.request.Request(url, method="HEAD", headers={"User-Agent": USER_AGENT})
            try:
                with urllib.request.urlopen(req, timeout=30) as r:
                    size = r.headers.get("Content-Length")
                    if p["source"].get("url") and size and int(size) != p["source"]["size"]:
                        errs.append(f"{p['id']}: the server reports {size} bytes, the ledger pins {p['source']['size']}")
            except (urllib.error.URLError, OSError) as e:
                errs.append(f"{p['id']}: {url} is unreachable: {e}")
    for e in errs:
        print(f"mce content: {e}", file=sys.stderr)
    if errs:
        return 1
    print(f"mce content: ledger ok ({len(ledger['packs'])} packs)")
    return 0


def cmd_fetch(args, ledger):
    pack = find_pack(ledger, args.pack)
    path = fetch_pack(pack, cache_dir(args.cache), args.file)
    print(path)
    return 0


def cmd_add(args, ledger):
    pack = find_pack(ledger, args.pack)
    archive = fetch_pack(pack, cache_dir(args.cache), args.file)
    entry = add_pack(pack, args.project, archive, args.only, args.dry_run)
    n = len(entry["files"])
    if args.dry_run:
        for rel in entry["files"]:
            print(f"would write {THIRD_PARTY}/{pack['id']}/{rel}")
        print(f"mce content: dry run, {n} files, nothing written")
        return 0
    lock = read_lock(args.project)
    old = next((e for e in lock["packs"] if e["id"] == pack["id"]), None)
    if old is not None and args.only:  # a partial re-add extends the recorded set
        entry["files"] = dict(sorted({**old["files"], **entry["files"]}.items()))
        entry["materials"] = sorted(set(old.get("materials", [])) | set(entry["materials"]))
    lock["packs"] = [e for e in lock["packs"] if e["id"] != pack["id"]] + [entry]
    write_lock(args.project, lock)
    write_credits(args.project, lock)
    print(f"mce content: added {pack['id']}: {n} files, {len(entry['materials'])} materials under "
          f"{THIRD_PARTY}/{pack['id']}/, credits updated ({pack['license']})")
    return 0


def cmd_verify(args, ledger):
    problems = verify_project(args.project, ledger)
    for p in problems:
        print(f"mce content: {p}", file=sys.stderr)
    if problems:
        return 1
    print(f"mce content: {args.project} third-party content ok ({len(read_lock(args.project)['packs'])} packs)")
    return 0


def cmd_credits(args, ledger):
    write_credits(args.project, read_lock(args.project))
    print(f"mce content: wrote {os.path.join(args.project, 'CREDITS.md')}")
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(prog="mce content", description="the open-licence content ledger (CC0 / CC-BY only)")
    ap.add_argument("--ledger", help="a ledger file (default: the engine's)")
    sub = ap.add_subparsers(dest="command", required=True, metavar="<command>")
    s = sub.add_parser("list", help="the packs in the ledger")
    s.add_argument("--kind", choices=KINDS)
    s.add_argument("--tag")
    s.add_argument("--license", choices=ALLOWED_LICENSES)
    s.add_argument("--json", action="store_true")
    s.set_defaults(fn=cmd_list)
    s = sub.add_parser("info", help="one pack's full ledger entry")
    s.add_argument("pack")
    s.set_defaults(fn=cmd_info)
    s = sub.add_parser("check", help="validate the ledger (--online: also HEAD every URL)")
    s.add_argument("--online", action="store_true")
    s.set_defaults(fn=cmd_check)
    s = sub.add_parser("fetch", help="download a pack's archive into the cache and verify its SHA-256")
    s.add_argument("pack")
    s.add_argument("--cache")
    s.add_argument("--file", help="use this downloaded file instead of the network (needed for manual packs)")
    s.set_defaults(fn=cmd_fetch)
    s = sub.add_parser("add", help="fetch a pack and cook it into a project's assets/third_party/")
    s.add_argument("pack")
    s.add_argument("project")
    s.add_argument("--only", action="append", help="only destination paths matching this glob (repeatable)")
    s.add_argument("--cache")
    s.add_argument("--file")
    s.add_argument("--dry-run", action="store_true")
    s.set_defaults(fn=cmd_add)
    s = sub.add_parser("verify", help="check that every third-party file in a project is recorded and openly licensed")
    s.add_argument("project", nargs="?", default=".")
    s.set_defaults(fn=cmd_verify)
    s = sub.add_parser("credits", help="rewrite the generated block of a project's CREDITS.md")
    s.add_argument("project", nargs="?", default=".")
    s.set_defaults(fn=cmd_credits)
    args = ap.parse_args(argv)
    try:
        ledger = load_ledger(args.ledger)
        if args.command != "check":
            errs = validate_ledger(ledger)
            if errs:
                raise ContentError("the ledger is invalid (run `mce content check`): " + errs[0])
        return args.fn(args, ledger)
    except ContentError as e:
        print(f"mce content: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
